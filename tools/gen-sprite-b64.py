#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate src/spriteb64.js from assets/player.png + assets/boss.png plus the
per-skin player_* and per-boss boss_* billboard sprites.

Why: file:// WebGL cannot upload file:// image textures (Chrome treats them as
null-origin/cross-origin and throws during texImage2D).  Data URIs are
same-origin, so they are WebGL-clean and work when the user double-clicks
index.html.  This file is committed and synced to www/ by scripts/sync-web.js.

Sprites are downscaled before encoding so the inline JS stays reasonably small
while still being crisp on the 42x50 ship / 80x80 boss billboards.
"""
import base64
import io
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "src")
ASSETS_DIR = os.path.join(ROOT, "assets")
OUT_FILE = os.path.join(SRC_DIR, "spriteb64.js")

# Legacy shared sprites (still used by the 2D fallback path).
# Per-skin / per-boss billboard textures for the 3D path.
NAMES = [
    "player", "boss",
    "player_cyan_knight", "player_crimson_falcon", "player_emerald",
    "player_violet", "player_stealth", "player_golden",
    "boss_sentinel", "boss_scorpion", "boss_carrier", "boss_core",
    "boss_phaser", "boss_void", "boss_weaverqueen",
]

lines = [
    "/* Auto-generated by tools/gen-sprite-b64.py */",
    "/* file:// WebGL cannot load file:// image textures (cross-origin/tainted). */",
    "/* Data URIs are same-origin and WebGL-clean for double-click play.        */",
    "window.DJFE_SPRITE_B64 = {",
]

def resize_png(path, max_size):
    """Resize a PNG so its largest side <= max_size, preserving aspect."""
    img = Image.open(path).convert("RGBA")
    w, h = img.size
    if w <= max_size and h <= max_size:
        return img
    ratio = min(max_size / w, max_size / h)
    new_size = (max(1, int(w * ratio)), max(1, int(h * ratio)))
    return img.resize(new_size, Image.LANCZOS)


for name in NAMES:
    path = os.path.join(ASSETS_DIR, name + ".png")
    max_size = 420 if name.startswith("boss_") or name == "boss" else 180
    img = resize_png(path, max_size)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    data = buf.getvalue()
    b64 = base64.b64encode(data).decode("ascii")
    lines.append(f'  {name}: "data:image/png;base64,{b64}",')

lines.append("};")

with open(OUT_FILE, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"wrote {OUT_FILE} ({len(NAMES)} sprite(s))")
